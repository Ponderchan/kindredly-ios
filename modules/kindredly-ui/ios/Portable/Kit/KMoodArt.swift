// Portable: this file imports SwiftUI only, so the 1.1.0 pure-Swift app can take it as is.

import SwiftUI

/*
 A MOOD ICON (owner, 2026-10-16): one of the 34 one-colour line faces the owner draws — 4 group
 icons (mood-group-calm … -low: a page that chose only a group's colour) and 30 faces
 (mood-sleepy …) — on the 24 grid, drawn from the same path data React Native draws (MoodFace in
 src/screens/notes/notes-glyphs.tsx). The table is Kit/KMoodArtData.swift, generated by
 scripts/gen-mood-art-swift.mjs from src/data/mood-line-art.ts, which scripts/import-mood-art.mjs
 writes from the SVG files in design/moods-line after checking every drawing rule; it is read
 once, the first time any mood icon is drawn.

     if let face = KMoodArt(key: note.icon, size: 22, ink: group.mood.faceInk, strokeScale: 1) {
       face
     } else {
       fallback                                        // no drawing for that key yet
     }

 `key` is the art key TS sends (src/data/moods.ts moodArtKey: "mood-<face>", "mood-group-<g>").
 The art is a template in a placeholder ink: KArt's template draw paints every mark in `ink`
 (the group's face ink, KMood.faceInk) and multiplies every stroke by `strokeScale`. The master
 strokes are 2 units; strokeStep(forFaceSize:) gives the optical step for a face size (2.4 at
 14pt or less, 2.0 up to 29pt, 1.75 from 30pt), so a scale is step / 2 (1.2 / 1 / 0.875).

 NO DRAWING, NO VIEW. The initializer fails — returns nil — for a key the table doesn't know and
 for an icon the owner hasn't delivered yet (paths: nil in the table), so the caller decides the
 fallback: KMoodChip tries the group's icon next, then the 10a line face (KLineGlyph). Nothing
 here draws a placeholder of its own.

 It draws the face only, never the tile (the tile's size and corners change at every site;
 KMoodChip draws it), and it is decorative: VoiceOver hears the mood in the label of whatever
 holds it.
 */
public struct KMoodArt: View {
  private let art: KArt
  private let size: CGFloat
  private let ink: Color
  private let strokeScale: CGFloat

  /// nil when `key` has no drawing (an unknown key, or an icon not delivered yet), so the caller
  /// can fall back.
  /// - Parameters:
  ///   - key: the art key ("mood-sleepy", "mood-group-low")
  ///   - size: the side of the face's square, in points
  ///   - ink: the colour every mark is painted in (the group's face ink)
  ///   - strokeScale: every stroke's width times this (the size's step over the master's 2)
  public init?(key: String, size: CGFloat, ink: Color, strokeScale: CGFloat = 1) {
    guard let art = Self.table[key] else { return nil }
    self.art = art
    self.size = size
    self.ink = ink
    self.strokeScale = strokeScale
  }

  public var body: some View {
    Canvas { context, box in
      art.draw(in: context, size: box, tint: ink, strokeScale: strokeScale)
    }
    .frame(width: size, height: size)
    .accessibilityHidden(true)
  }

  // ── the strokes ──

  /// The width every mark's stroke is drawn at in the design files (design/moods-line: stroke 2).
  public static let masterStroke: CGFloat = 2

  /// The stroke for a face of `faceSize` points, in 24-grid units: 2.4 at 14pt or less (the 12pt
  /// legend, the 13pt date chip), 2.0 up to 29pt, 1.75 from 30pt — so the line stays between 1.2
  /// and 2.3pt on screen. React Native's moodStrokeStep is the same.
  public static func strokeStep(forFaceSize faceSize: CGFloat) -> CGFloat {
    faceSize <= 14 ? 2.4 : faceSize < 30 ? 2 : 1.75
  }

  // ── the table ──

  /// Every drawn icon's art, read once.
  private static let table: [String: KArt] = {
    var out: [String: KArt] = [:]
    for entry in KMoodArtData.moods {
      if let paths = entry.paths, !paths.isEmpty {
        out[entry.key] = KArt(grid: KMoodArtData.grid, paths: paths)
      }
    }
    return out
  }()

  /// Every icon the table lists, drawn or not, in src/data/moods.ts order (each group's icon, then
  /// its faces).
  public static let keys: [String] = KMoodArtData.moods.map(\.key)

  /// The icons not drawn yet (paths: nil): a caller falls back for each of these.
  public static let undrawn: [String] = KMoodArtData.moods.filter { $0.paths?.isEmpty ?? true }.map(\.key)

  /// Whether this key draws its own art; false means the caller's fallback.
  public static func hasArt(_ key: String) -> Bool {
    table[key] != nil
  }
}

/// One mood icon in the generated table (Kit/KMoodArtData.swift): its art key and its marks in the
/// template ink, or nil when it isn't drawn yet.
struct KMoodArtEntry: Sendable {
  let key: String
  let paths: [KArtPath]?

  init(_ key: String, paths: [KArtPath]?) {
    self.key = key
    self.paths = paths
  }
}
