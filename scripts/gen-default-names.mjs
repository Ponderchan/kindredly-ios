// node scripts/gen-default-names.mjs            write src/data/default-names/<lang>.ts
// node scripts/gen-default-names.mjs --check    exit 1 if any of them is out of date
//
// The default names for strangers ("Postmark names", .claude/ui10a-research/identity/
// default-names-strategy.md) are 64 postmarks x 128 keepsakes per language, plus a
// blocklist of pairs. Native editors froze each language as a JSON "final" in
// .claude/ui10a-research/identity/names/. This script turns those nine files into the typed
// lists src/lib/default-name.ts reads, so a word is changed once, in the final, and this
// script is run again.
//
// Nothing is guessed. A list of the wrong size, a repeated word, a word in both lists, a
// blocked pair out of range or a language that breaks the build gate (more than 5% of
// pairs blocked, or a keepsake with fewer than 48 usable postmarks; strategy §2) is an
// error, not a fallback: a bad list should stop the script, not reach a screen.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";

const FINALS = new URL("../.claude/ui10a-research/identity/names/", import.meta.url);
const OUT = new URL("../src/data/default-names/", import.meta.url);
const CHECK = process.argv.includes("--check");

// Lang id (src/lib/i18n.ts) -> the final's file name and the "lang" it declares
const LANGS = [
  ["en", "en", "en"],
  ["es", "es", "es"],
  ["pt", "pt", "pt-BR"],
  ["id", "id", "id"],
  ["fr", "fr", "fr"],
  ["de", "de", "de"],
  ["it", "it", "it"],
  ["ja", "ja", "ja"],
  ["ko", "ko", "ko"],
];
const P = 64;
const K = 128;
const MAX_BLOCKED = 0.05;
const MIN_USABLE = 48;

const errors = [];
const fail = (lang, msg) => errors.push(`${lang}: ${msg}`);

function load(lang, file, declared) {
  const src = new URL(`${file}.final.json`, FINALS);
  if (!existsSync(src)) {
    fail(lang, `missing ${src.pathname}`);
    return null;
  }
  const d = JSON.parse(readFileSync(src, "utf8"));
  if (d.lang !== declared) fail(lang, `the final says lang "${d.lang}", expected "${declared}"`);
  const post = d.postmarks;
  const keep = d.keepsakes;
  if (!Array.isArray(post) || post.length !== P) fail(lang, `${post?.length} postmarks, expected ${P}`);
  if (!Array.isArray(keep) || keep.length !== K) fail(lang, `${keep?.length} keepsakes, expected ${K}`);
  if (!Array.isArray(post) || !Array.isArray(keep)) return null;
  for (const [name, list] of [["postmark", post], ["keepsake", keep]]) {
    const seen = new Set();
    for (const w of list) {
      if (typeof w !== "string" || !w.trim() || w !== w.trim()) fail(lang, `bad ${name} ${JSON.stringify(w)}`);
      if (seen.has(w)) fail(lang, `${name} "${w}" appears twice`);
      seen.add(w);
    }
  }
  for (const w of post) if (keep.includes(w)) fail(lang, `"${w}" is in both lists`);

  const blocked = new Set();
  for (const pair of d.blockedPairs ?? []) {
    const [p, k] = pair;
    if (pair.length !== 2 || !Number.isInteger(p) || !Number.isInteger(k) || p < 0 || p >= P || k < 0 || k >= K) {
      fail(lang, `blocked pair ${JSON.stringify(pair)} is out of range`);
      continue;
    }
    blocked.add(p * K + k);
  }
  if (blocked.size > MAX_BLOCKED * P * K) fail(lang, `${blocked.size} pairs blocked, the gate is ${MAX_BLOCKED * P * K}`);
  for (let k = 0; k < K; k++) {
    let usable = 0;
    for (let p = 0; p < P; p++) if (!blocked.has(p * K + k)) usable++;
    if (usable < MIN_USABLE) fail(lang, `keepsake "${keep[k]}" has ${usable} usable postmarks, the gate is ${MIN_USABLE}`);
  }
  const block = [...blocked].sort((a, b) => a - b).map((i) => [Math.floor(i / K), i % K]);

  // kana readings travel only when they cover every item (ja); partial lists are review notes
  let readings = null;
  const r = d.readings;
  if (r && typeof r === "object" && [...post, ...keep].every((w) => typeof r[w] === "string")) {
    readings = Object.fromEntries([...post, ...keep].map((w) => [w, r[w]]));
  }
  return { post, keep, block, readings };
}

function rows(items, per, indent) {
  const out = [];
  for (let i = 0; i < items.length; i += per) out.push(indent + items.slice(i, i + per).join(", ") + ",");
  return out.join("\n");
}

function render(lang, file, l) {
  const q = (s) => JSON.stringify(s);
  const parts = [
    `// GENERATED by scripts/gen-default-names.mjs from`,
    `// .claude/ui10a-research/identity/names/${file}.final.json. Do not edit: change the final and`,
    `// run the script again. Slots are frozen (strategy §3.5): replace a word in its slot, never reorder.`,
    `import type { DefaultNameList } from "../../lib/default-name";`,
    ``,
    `const ${lang}: DefaultNameList = {`,
    `  post: [`,
    rows(l.post.map(q), 8, "    "),
    `  ],`,
    `  keep: [`,
    rows(l.keep.map(q), 8, "    "),
    `  ],`,
    `  block: [`,
    l.block.length ? rows(l.block.map(([p, k]) => `[${p}, ${k}]`), 12, "    ") : null,
    `  ],`,
  ];
  if (l.readings) {
    parts.push(`  readings: {`);
    parts.push(Object.entries(l.readings).map(([w, r]) => `    ${q(w)}: ${q(r)},`).join("\n"));
    parts.push(`  },`);
  }
  parts.push(`};`, ``, `export default ${lang};`, ``);
  return parts.filter((x) => x !== null).join("\n");
}

const outputs = [];
for (const [lang, file, declared] of LANGS) {
  const l = load(lang, file, declared);
  if (l) outputs.push([lang, render(lang, file, l)]);
}
if (errors.length) {
  console.error("gen-default-names: refusing to write\n  " + errors.join("\n  "));
  process.exit(1);
}

let stale = 0;
if (!CHECK) mkdirSync(OUT, { recursive: true });
for (const [lang, text] of outputs) {
  const dst = new URL(`${lang}.ts`, OUT);
  const now = existsSync(dst) ? readFileSync(dst, "utf8") : null;
  if (now === text) continue;
  if (CHECK) {
    console.error(`gen-default-names: src/data/default-names/${lang}.ts is out of date`);
    stale++;
  } else {
    writeFileSync(dst, text);
    console.log(`wrote src/data/default-names/${lang}.ts`);
  }
}
if (CHECK && stale) process.exit(1);
if (CHECK) console.log("gen-default-names: all nine lists are up to date");
