// node scripts/gen-stranger-names-json.mjs                 write src/data/stranger-names.v1.json
// node scripts/gen-stranger-names-json.mjs --web "<web repo>/app/engine/stranger-names.v1.json"
//                                                          also write the web's byte-identical copy
// node scripts/gen-stranger-names-json.mjs --check [--web …]  exit 1 if a copy is out of date
//
// THE COURIER NAMES' LISTS AS ONE JSON FILE, FOR THE WEB (identity plan §3.2).
// The app names strangers from the typed lists in src/data/default-names/<lang>.ts (written by
// scripts/gen-default-names.mjs from the native finals). The web (~/Desktop/claude 项目/kindredly,
// no TypeScript) needs exactly the same words, in exactly the same slots, or one stranger would
// wear two names. So this script turns those nine lists, and the template each language joins
// them with, into one JSON file, written byte for byte the same into both repos:
//   this repo   src/data/stranger-names.v1.json      (not imported by the app; the lock's twin)
//   the web     app/engine/stranger-names.v1.json    (imported by app/engine/names-core.js)
// Both test suites (src/lib/stranger-name.test.ts and the web's scripts/names-core.test.mjs)
// lock the file's sha256 and the shared vectors in design/identity/stranger-names.v1.vectors.json,
// so a list that moves on one side and not the other fails a test.
//
// Slots are frozen (strategy §3.5): a word replaced in its slot or a pair blocked is a new
// version — change the final, run gen-default-names, run this, re-lock the sha256 and the vectors.
//
// The templates mirror src/lib/default-name.ts (KEEPSAKE_FIRST, NO_SPACE): "order" is "pk"
// (postmark, then keepsake) or "kp"; "sep" is what joins them. A test checks they agree with
// pairName() for every language.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(HERE, "../src/data/stranger-names.v1.json");
const CHECK = process.argv.includes("--check");

const webAt = process.argv.indexOf("--web");
let WEB = null;
if (webAt >= 0) {
  const p = process.argv[webAt + 1];
  if (!p || p.startsWith("--")) {
    console.error('gen-stranger-names-json: --web needs the path of the web\'s copy, e.g. --web "<web repo>/app/engine/stranger-names.v1.json"');
    process.exit(2);
  }
  WEB = resolve(p);
}

// the app's order (src/lib/default-name.ts DEFAULT_NAME_LISTS); never reorder
const LANGS = ["en", "es", "pt", "id", "fr", "de", "it", "ja", "ko"];
const KEEPSAKE_FIRST = new Set(["es", "pt", "fr", "it", "id"]);
const NO_SPACE = new Set(["de", "ja"]);
const P = 64;
const K = 128;

const lists = {};
for (const lang of LANGS) {
  // the data files only `import type`, which Node's type stripping erases: no resolver needed
  const mod = await import(resolve(HERE, `../src/data/default-names/${lang}.ts`));
  const l = mod.default;
  if (!l || l.post?.length !== P || l.keep?.length !== K) {
    console.error(`gen-stranger-names-json: ${lang}: expected ${P} postmarks and ${K} keepsakes`);
    process.exit(1);
  }
  lists[lang] = {
    order: KEEPSAKE_FIRST.has(lang) ? "kp" : "pk",
    sep: NO_SPACE.has(lang) ? "" : " ",
    post: [...l.post],
    keep: [...l.keep],
    block: l.block.map(([p, k]) => [p, k]),
  };
}

/* One array per line, so a diff shows which list moved; keys in a fixed order. */
const j = (v) => JSON.stringify(v);
const lines = [
  "{",
  `"v": 1,`,
  `"about": ${j("Courier names for strangers (identity plan §3): 64 postmarks x 128 keepsakes per language and the blocked [postmark, keepsake] pairs. GENERATED by kindredly-ios scripts/gen-stranger-names-json.mjs from src/data/default-names; byte-identical in both repos. Do not edit.")},`,
  `"P": ${P},`,
  `"K": ${K},`,
  `"langs": ${j(LANGS)},`,
  `"lists": {`,
];
LANGS.forEach((lang, i) => {
  const l = lists[lang];
  lines.push(`${j(lang)}: {`);
  lines.push(`"order": ${j(l.order)}, "sep": ${j(l.sep)},`);
  lines.push(`"post": ${j(l.post)},`);
  lines.push(`"keep": ${j(l.keep)},`);
  lines.push(`"block": ${j(l.block)}`);
  lines.push(i === LANGS.length - 1 ? "}" : "},");
});
lines.push("}", "}", "");
const text = lines.join("\n");
JSON.parse(text); // it must be JSON

let stale = 0;
for (const path of [OUT, WEB].filter(Boolean)) {
  const have = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (have === text) {
    console.log(`up to date  ${path}`);
    continue;
  }
  if (CHECK) {
    console.log(`OUT OF DATE ${path}`);
    stale++;
    continue;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
  console.log(`wrote       ${path}`);
}
if (stale) process.exit(1);
